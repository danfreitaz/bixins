import type { ItemKey, Need, Species, RegionKey } from "./config";
export type Point = { x: number; y: number };
export type Bixin = Point & {
  id: string;
  species: Species;
  name: string;
  bornAt: number;
  needs: Record<Need, number>;
  activity: string;
  path: Point[];
  targetId?: string;
  careAt: number;
  role: "A" | "B";
  traits: string[];
  origin?: RegionKey;
  parentA?: string;
  parentB?: string;
  variant?: string;
  genderLabel?: string;
  genome?: Genome;
  lastBredAt?: number;
  partnerId?: string;
};
export type Genome = {
  primary: number;
  secondary: number;
  pattern: "liso" | "pintado" | "listrado";
  size: "pequeno" | "médio" | "fofucho";
  ears: number;
  tail: number;
  crest: number;
  temperamentBias: number;
  energyBias: number;
};
export type Relationship = {
  a: string;
  b: string;
  affinity: number;
  interactions: number;
  lastAt: number;
  friendshipAt?: number;
  lastKind?: string;
};
export type Nest = {
  itemId: string;
  a: string;
  b: string;
  preparedAt: number;
  settledAt: number | null;
  seed: number;
};
export type OwnedItem = Point & {
  id: string;
  key: ItemKey;
  placed: boolean;
  stock: number;
  level?: number;
  rotation?: 0 | 1;
};
export type Egg = Point & {
  id: string;
  species: Species;
  readyAt: number | null;
  first: boolean;
  origin?: RegionKey;
  parentA?: string;
  parentB?: string;
  genome?: Genome;
  traits?: string[];
  variant?: string;
  role?: "A" | "B";
};
export type GameEvent = {
  id: string;
  at: number;
  text: string;
  milestone?: boolean;
};
export type Ledger = {
  id: string;
  at: number;
  delta: number;
  balance: number;
  kind: string;
};
export type Expedition = {
  id: string;
  region: RegionKey;
  startedAt: number;
  endsAt: number;
  seed: number;
  reward: { species?: Species; credits: number; item?: ItemKey };
};
export type MissionState = {
  completedAt: number | null;
  claimedAt: number | null;
};
export type Transfer = { id: string; bixin: Bixin; at: number; price: number };
export type Game = {
  schemaVersion?: number;
  eventSequence?: number;
  xp?: number;
  version: number;
  name: string;
  credits: number;
  width: number;
  height: number;
  capacity: number;
  level?: number;
  lastSimulated: number;
  lastIncome: number;
  food: number;
  foodDay: number;
  seed: number;
  bixins: Bixin[];
  items: OwnedItem[];
  eggs: Egg[];
  events: GameEvent[];
  ledger: Ledger[];
  discoveries: Species[];
  missions?: Record<string, MissionState>;
  expedition?: Expedition | null;
  expeditionsCompleted?: number;
  careCount?: number;
  incomeCycles?: number;
  transfers?: Transfer[];
  discoveryCounts?: Partial<Record<Species, number>>;
  relationships?: Record<string, Relationship>;
  nest?: Nest | null;
  milestones?: GameEvent[];
};
